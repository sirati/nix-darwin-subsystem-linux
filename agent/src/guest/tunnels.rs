//! Pure planning for the tunnel PipeWire instance: node naming, config
//! rendering, and deciding when the child must restart.

use std::collections::HashSet;
use std::fmt::Write;

use crate::protocol::{AudioState, Device};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    Sink,
    Source,
}

impl Mode {
    pub fn as_str(self) -> &'static str {
        match self {
            Mode::Sink => "sink",
            Mode::Source => "source",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Tunnel {
    pub mode: Mode,
    pub pulse_name: String,
    pub node_name: String,
    pub description: String,
}

pub fn slugify(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars().flat_map(char::to_lowercase) {
        if c.is_ascii_alphanumeric() || c == '-' {
            out.push(c);
        } else if !out.ends_with('_') {
            out.push('_');
        }
    }
    let out = out.trim_matches('_');
    if out.is_empty() {
        "device".to_string()
    } else {
        out.to_string()
    }
}

/// Slugs in input order; repeats get `_2`, `_3`, ... skipping taken names.
pub fn assign_slugs<'a>(descriptions: impl IntoIterator<Item = &'a str>) -> Vec<String> {
    let mut used = HashSet::new();
    let mut out = Vec::new();
    for d in descriptions {
        let base = slugify(d);
        let mut slug = base.clone();
        let mut n = 2;
        while used.contains(&slug) {
            slug = format!("{base}_{n}");
            n += 1;
        }
        used.insert(slug.clone());
        out.push(slug);
    }
    out
}

fn plan_mode(devices: &[Device], mode: Mode) -> Vec<Tunnel> {
    // Sorted so node names don't depend on the host's enumeration order.
    let mut sorted: Vec<&Device> = devices.iter().collect();
    sorted.sort_by(|a, b| (&a.description, &a.pulse_name).cmp(&(&b.description, &b.pulse_name)));
    sorted.dedup_by(|a, b| a.pulse_name == b.pulse_name);
    let slugs = assign_slugs(sorted.iter().map(|d| d.description.as_str()));
    sorted
        .into_iter()
        .zip(slugs)
        .map(|(d, slug)| Tunnel {
            mode,
            pulse_name: d.pulse_name.clone(),
            node_name: format!("mac.{}.{slug}", mode.as_str()),
            description: d.description.clone(),
        })
        .collect()
}

pub fn plan(state: &AudioState) -> Vec<Tunnel> {
    let mut t = plan_mode(&state.sinks, Mode::Sink);
    t.extend(plan_mode(&state.sources, Mode::Source));
    t
}

/// SPA-JSON string literal.
fn spa_str(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => out.push(' '),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Client-only instance, same shape as PipeWire's filter-chain.conf: no
/// server socket, it just connects to the user's daemon and hosts the nodes.
pub fn render_config(tunnels: &[Tunnel], pulse_server: &str) -> String {
    let mut s = String::from(
        "# Generated by linux-vm-agent. Do not edit.
context.properties = {
    log.level = 0
}
context.spa-libs = {
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}
context.modules = [
    { name = libpipewire-module-rt
        args = { }
        flags = [ ifexists nofail ]
    }
    { name = libpipewire-module-protocol-native }
    { name = libpipewire-module-client-node }
    { name = libpipewire-module-adapter }
",
    );
    for t in tunnels {
        let _ = write!(
            s,
            "    {{ name = libpipewire-module-pulse-tunnel
        args = {{
            tunnel.mode = {mode}
            pulse.server.address = {server}
            target.object = {target}
            node.name = {name}
            node.description = {desc}
            reconnect.interval.ms = 2000
        }}
    }}
",
            mode = t.mode.as_str(),
            server = spa_str(pulse_server),
            target = spa_str(&t.pulse_name),
            name = spa_str(&t.node_name),
            desc = spa_str(&t.description),
        );
    }
    s.push_str("]\n");
    s
}

/// Configured defaults as node names.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Defaults {
    pub sink: Option<String>,
    pub source: Option<String>,
}

impl Defaults {
    pub fn is_empty(&self) -> bool {
        self.sink.is_none() && self.source.is_none()
    }
}

fn node_for(tunnels: &[Tunnel], mode: Mode, pulse_name: Option<&str>) -> Option<String> {
    let want = pulse_name?;
    tunnels.iter().find(|t| t.mode == mode && t.pulse_name == want).map(|t| t.node_name.clone())
}

#[derive(Debug, PartialEq, Eq)]
pub struct Decision {
    /// New tunnel set; the child must be (re)started (or stopped if empty).
    pub restart: Option<Vec<Tunnel>>,
    /// Defaults changed without a restart; apply them to the running nodes.
    pub apply_defaults: bool,
}

#[derive(Default)]
pub struct Reconciler {
    tunnels: Option<Vec<Tunnel>>,
    defaults: Defaults,
}

impl Reconciler {
    pub fn update(&mut self, state: &AudioState) -> Decision {
        let tunnels = plan(state);
        let defaults = Defaults {
            sink: node_for(&tunnels, Mode::Sink, state.default_sink.as_deref()),
            source: node_for(&tunnels, Mode::Source, state.default_source.as_deref()),
        };
        let restart = self.tunnels.as_ref() != Some(&tunnels);
        let defaults_changed = defaults != self.defaults;
        self.tunnels = Some(tunnels.clone());
        self.defaults = defaults;
        Decision {
            restart: restart.then_some(tunnels),
            apply_defaults: !restart && defaults_changed && !self.defaults.is_empty(),
        }
    }

    pub fn defaults(&self) -> &Defaults {
        &self.defaults
    }
}

/// `node.name`s of all nodes in `pw-dump` output.
pub fn pw_dump_node_names(json: &str) -> HashSet<String> {
    let Ok(serde_json::Value::Array(objs)) = serde_json::from_str(json) else { return HashSet::new() };
    objs.iter()
        .filter(|o| o["type"] == "PipeWire:Interface:Node")
        .filter_map(|o| o["info"]["props"]["node.name"].as_str().map(str::to_string))
        .collect()
}

/// argv (without the program) for setting a configured default.
pub fn metadata_args(mode: Mode, node_name: &str) -> Vec<String> {
    vec![
        "-n".into(),
        "default".into(),
        "0".into(),
        format!("default.configured.audio.{}", mode.as_str()),
        serde_json::json!({ "name": node_name }).to_string(),
        "Spa:String:JSON".into(),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    fn dev(p: &str, d: &str) -> Device {
        Device { pulse_name: p.into(), description: d.into() }
    }

    fn sample() -> AudioState {
        AudioState {
            sinks: vec![dev("Channel_1__Channel_2", "WH-1000XM5"), dev("1__2", "MacBook Neo Speakers")],
            sources: vec![dev("Channel_1", "WH-1000XM5"), dev("1", "MacBook Neo Microphone")],
            default_sink: Some("Channel_1__Channel_2".into()),
            default_source: Some("1".into()),
        }
    }

    #[test]
    fn slugs() {
        assert_eq!(slugify("WH-1000XM5"), "wh-1000xm5");
        assert_eq!(slugify("MacBook Neo Speakers"), "macbook_neo_speakers");
        assert_eq!(slugify("  Ünïcode  / weird!! "), "n_code_weird");
        assert_eq!(slugify("***"), "device");
        assert_eq!(slugify("a.b\"c"), "a_b_c");
    }

    #[test]
    fn slug_dedup() {
        assert_eq!(assign_slugs(["USB Audio", "USB Audio", "USB-Audio", "usb audio"]), ["usb_audio", "usb_audio_2", "usb-audio", "usb_audio_3"]);
        // A literal "x_2" description must not collide with a generated suffix.
        assert_eq!(assign_slugs(["x_2", "x", "x"]), ["x_2", "x", "x_3"]);
        assert_eq!(assign_slugs(["", "!"]), ["device", "device_2"]);
    }

    #[test]
    fn plan_is_order_independent() {
        let mut s = sample();
        let a = plan(&s);
        s.sinks.reverse();
        s.sources.reverse();
        assert_eq!(plan(&s), a);
        let names: Vec<_> = a.iter().map(|t| t.node_name.as_str()).collect();
        assert_eq!(names, ["mac.sink.macbook_neo_speakers", "mac.sink.wh-1000xm5", "mac.source.macbook_neo_microphone", "mac.source.wh-1000xm5"]);
    }

    #[test]
    fn config_golden() {
        let state = AudioState {
            sinks: vec![dev("Channel_1__Channel_2", "WH-1000XM5")],
            sources: vec![dev("1", "MacBook \"Neo\" Microphone")],
            ..Default::default()
        };
        let got = render_config(&plan(&state), "unix:/run/user/1000/mac-pulse.sock");
        let want = r#"# Generated by linux-vm-agent. Do not edit.
context.properties = {
    log.level = 0
}
context.spa-libs = {
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}
context.modules = [
    { name = libpipewire-module-rt
        args = { }
        flags = [ ifexists nofail ]
    }
    { name = libpipewire-module-protocol-native }
    { name = libpipewire-module-client-node }
    { name = libpipewire-module-adapter }
    { name = libpipewire-module-pulse-tunnel
        args = {
            tunnel.mode = sink
            pulse.server.address = "unix:/run/user/1000/mac-pulse.sock"
            target.object = "Channel_1__Channel_2"
            node.name = "mac.sink.wh-1000xm5"
            node.description = "WH-1000XM5"
            reconnect.interval.ms = 2000
        }
    }
    { name = libpipewire-module-pulse-tunnel
        args = {
            tunnel.mode = source
            pulse.server.address = "unix:/run/user/1000/mac-pulse.sock"
            target.object = "1"
            node.name = "mac.source.macbook_neo_microphone"
            node.description = "MacBook \"Neo\" Microphone"
            reconnect.interval.ms = 2000
        }
    }
]
"#;
        assert_eq!(got, want);
    }

    #[test]
    fn only_device_set_changes_restart() {
        let mut r = Reconciler::default();
        let s = sample();

        let d = r.update(&s);
        assert_eq!(d.restart.as_ref().map(Vec::len), Some(4));
        assert!(!d.apply_defaults, "restart applies defaults itself");
        assert_eq!(r.defaults().sink.as_deref(), Some("mac.sink.wh-1000xm5"));
        assert_eq!(r.defaults().source.as_deref(), Some("mac.source.macbook_neo_microphone"));

        // Identical state: nothing.
        assert_eq!(r.update(&s), Decision { restart: None, apply_defaults: false });

        // Same devices, reordered: nothing.
        let mut reordered = s.clone();
        reordered.sinks.reverse();
        assert_eq!(r.update(&reordered), Decision { restart: None, apply_defaults: false });

        // Only the default changes: no restart, apply defaults.
        let mut s2 = s.clone();
        s2.default_sink = Some("1__2".into());
        assert_eq!(r.update(&s2), Decision { restart: None, apply_defaults: true });
        assert_eq!(r.defaults().sink.as_deref(), Some("mac.sink.macbook_neo_speakers"));

        // Default becomes unknown: no restart, nothing to apply.
        let mut s3 = s2.clone();
        s3.default_sink = None;
        s3.default_source = None;
        assert_eq!(r.update(&s3), Decision { restart: None, apply_defaults: false });

        // Device added: restart.
        let mut s4 = s2.clone();
        s4.sinks.push(dev("AirPods", "AirPods Pro"));
        assert_eq!(r.update(&s4).restart.map(|t| t.len()), Some(5));

        // Description change renames the node: restart.
        let mut s5 = s4.clone();
        s5.sinks[2].description = "Kitchen".into();
        assert!(r.update(&s5).restart.is_some());

        // All gone: restart with empty set (stop the child).
        assert_eq!(r.update(&AudioState::default()).restart, Some(vec![]));
    }

    #[test]
    fn pw_dump_parsing() {
        let json = r#"[
          {"id":0,"type":"PipeWire:Interface:Core","info":{"props":{"node.name":"nope"}}},
          {"id":40,"type":"PipeWire:Interface:Node","info":{"props":{"node.name":"mac.sink.wh-1000xm5","media.class":"Audio/Sink"}}},
          {"id":41,"type":"PipeWire:Interface:Node","info":{"props":{}}},
          {"id":42,"type":"PipeWire:Interface:Metadata","props":{"metadata.name":"default"}}
        ]"#;
        let names = pw_dump_node_names(json);
        assert_eq!(names.into_iter().collect::<Vec<_>>(), ["mac.sink.wh-1000xm5"]);
        assert!(pw_dump_node_names("not json").is_empty());
    }

    #[test]
    fn metadata_argv() {
        assert_eq!(
            metadata_args(Mode::Source, "mac.source.x\"y"),
            ["-n", "default", "0", "default.configured.audio.source", r#"{"name":"mac.source.x\"y"}"#, "Spa:String:JSON"]
        );
    }
}
